function getDeviceLanguage(): string {
  const deviceLocale = Localization.getLocales()[0]?.languageCode || 'en';

  // Map device language to supported locales
  if (deviceLocale.startsWith('bs')) {
    return 'bs-BS';
  }

  return 'en-US';
}

