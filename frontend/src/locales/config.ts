export const APP_LOCALES = ["bs-BS", "en-US"] as const;
export type AppLocale = (typeof APP_LOCALES)[number];
export const LOCALE_STORAGE_KEY = "boiler.locale";

export const isAppLocale = (value: string): value is AppLocale =>
  (APP_LOCALES as readonly string[]).includes(value);

export const normalizeAppLocale = (raw?: string | null): AppLocale => {
  if (!raw) return "bs-BS";
  const lower = raw.toLowerCase();
  if (lower.startsWith("en")) return "en-US";
  if (isAppLocale(raw)) return raw;
  return "bs-BS";
};

export const setAppLanguage = async (raw: string): Promise<AppLocale> => {
  const locale = normalizeAppLocale(raw);
  try {
    localStorage.setItem(LOCALE_STORAGE_KEY, locale);
  } catch {
    /* private mode */
  }
  await i18n.changeLanguage(locale);
  return locale;
};

// Initialize i18n
i18n.use(initReactI18next).init({
  resources: {
    "en-US": { translation: enUS },
    "bs-BS": { translation: bsBS },
  },
  lng: getDefaultLanguage(),
  fallbackLng: "en-US",
  interpolation: {
    escapeValue: false,
  },
});

function getDefaultLanguage(): string {
  try {
    const stored = localStorage.getItem(LOCALE_STORAGE_KEY);
    if (stored && isAppLocale(stored)) return stored;
  } catch {
    /* private mode */
  }
  // Product default is Bosnian; honour explicit English browser prefs.
  const browserLang = navigator.language || "bs-BS";
  if (browserLang.toLowerCase().startsWith("en")) {
    return "en-US";
  }
  return "bs-BS";
}

/**
 * FE2-6: `<html lang>` mora odražavati stvarno odabrani jezik, a ne statički
 * "en" iz index.html. Bez ovoga čitači ekrana čitaju bosanski tekst engleskim
 * izgovorom.
 *
 * Namjerno u modulu, a NE inline skriptom u index.html: CSP postavlja
 * `script-src 'self'`, pa bi inline skripta bila blokirana kad CSP pređe iz
 * Report-Only u obavezujući režim.
 */
function applyDocumentLanguage(lng: string) {
  document.documentElement.lang = lng;
}

applyDocumentLanguage(i18n.language);
i18n.on("languageChanged", applyDocumentLanguage);

export default i18n;
